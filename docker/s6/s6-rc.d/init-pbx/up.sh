#!/bin/sh
# BetterPBX one-shot first-boot initialisation.
#
# Runs as root before Asterisk, the API, and fail2ban. It must be idempotent: restarting
# the container against the same /data must never overwrite the operator's configuration,
# TLS material, tokens, or Git history.
set -eu

DATA="${PBX_DATA_DIR:-/data}"
BOOTSTRAP_CONFIG="/opt/better-pbx/bootstrap/asterisk"
BOOTSTRAP_MODEL="/opt/better-pbx/bootstrap/pbx.yaml"

log() {
  printf '[better-pbx] %s\n' "$*"
}

install_dir() {
  # install_dir <mode> <owner> <group> <path...>
  mode="$1"
  owner="$2"
  group="$3"
  shift 3
  install -d -m "$mode" -o "$owner" -g "$group" "$@"
}

install_dir 0770 root pbx "$DATA"
install_dir 0770 pbx pbx "$DATA/config" "$DATA/runtime"
install_dir 0750 pbx pbx "$DATA/config/asterisk"
install_dir 0770 asterisk pbx "$DATA/voicemail" "$DATA/log" "$DATA/sounds"
# Asterisk's spool directory is /data, so create the standard subdirectories up front. They are
# all Asterisk-owned and never committed to the configuration repository.
for spool in dictate meetme monitor outgoing outgoing_done qlog recording system tmp; do
  install_dir 0770 asterisk pbx "$DATA/$spool"
done
install_dir 0770 asterisk pbx "$DATA/log/cdr-csv"
install_dir 0770 root pbx "$DATA/fail2ban"
install_dir 0770 asterisk pbx "$DATA/runtime/tls"
install_dir 0770 asterisk pbx /run/asterisk
install_dir 0755 root pbx /run/fail2ban

# Timezone is an operator setting. Fall back to UTC when the zoneinfo file is missing.
TZ_VALUE="${TZ:-UTC}"
if [ -f "/usr/share/zoneinfo/${TZ_VALUE}" ]; then
  ln -snf "/usr/share/zoneinfo/${TZ_VALUE}" /etc/localtime
  printf '%s\n' "$TZ_VALUE" >/etc/timezone
else
  log "timezone ${TZ_VALUE} not found; keeping UTC"
fi

fresh_boot=0
if [ ! -d "$DATA/config/.git" ]; then
  fresh_boot=1
fi

# Bootstrap configuration is copied only when it is absent. Existing volumes are never
# rewritten: upgrades are a deliberate migration in a later phase.
if [ ! -f "$DATA/config/asterisk/asterisk.conf" ]; then
  cp -a "${BOOTSTRAP_CONFIG}/." "$DATA/config/asterisk/"
  log "installed bootstrap Asterisk configuration"
fi

if [ ! -f "$DATA/config/pbx.yaml" ]; then
  created_at="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  sed "s/__CREATED_AT__/${created_at}/g" "$BOOTSTRAP_MODEL" >"$DATA/config/pbx.yaml"
  log "installed bootstrap model /data/config/pbx.yaml"
fi

# Runtime ACL is generated by the API in later phases. Until then, the safe default is
# deny-all; the file is outside Git because it changes without a configuration snapshot.
if [ ! -f "$DATA/runtime/pjsip-acl.conf" ]; then
  umask 027
  cat >"$DATA/runtime/pjsip-acl.conf" <<'EOF'
; Generated at runtime by BetterPBX. Deny by default; the API adds whitelist permits.
[global-acl]
type = acl
deny = 0.0.0.0/0.0.0.0
EOF
fi

# OpenSSL defaults for Asterisk TLS/SRTP. Restrict ECDHE curves to widely supported ones
# to avoid 'wrong curve' handshakes with older SIP phones, while keeping RSA fallbacks.
if [ ! -s "$DATA/runtime/tls/openssl.cnf" ]; then
  umask 022
  cat >"$DATA/runtime/tls/openssl.cnf" <<'EOF'
openssl_conf = default_conf
[default_conf]
ssl_conf = ssl_sect
[ssl_sect]
system_default = system_default_sect
[system_default_sect]
MinProtocol = TLSv1.2
Curves = prime256v1:X25519:secp384r1:secp521r1
EOF
  log "generated OpenSSL defaults for TLS"
fi

# Self-signed SIP TLS material. The key stays readable only by Asterisk, which also owns
# the key file even though the API owns the rest of the runtime directory.
if [ ! -s "$DATA/runtime/tls/sip.key" ] || [ ! -s "$DATA/runtime/tls/sip.crt" ]; then
  umask 077
  openssl req -x509 -newkey rsa:3072 -sha256 -nodes -days 825 \
    -keyout "$DATA/runtime/tls/sip.key" \
    -out "$DATA/runtime/tls/sip.crt" \
    -subj "/CN=better-pbx" \
    -addext "subjectAltName=DNS:better-pbx" >/dev/null 2>&1
  log "generated self-signed SIP TLS certificate"
fi
chown asterisk:pbx "$DATA/runtime/tls" "$DATA/runtime/tls/sip.key" "$DATA/runtime/tls/sip.crt"
chmod 0770 "$DATA/runtime/tls"
chmod 0600 "$DATA/runtime/tls/sip.key"
chmod 0640 "$DATA/runtime/tls/sip.crt"

# Internal token is used by fail2ban to call the loopback ban endpoint. It is never
# committed and is re-created only if missing.
if [ ! -s "$DATA/runtime/internal-token" ]; then
  umask 077
  openssl rand -hex 32 >"$DATA/runtime/internal-token"
  log "generated internal API token"
fi

# One-time setup code. PBX_SETUP_TOKEN makes automated provisioning possible; otherwise a
# random, human-readable code is generated. The API removes the file after setup.
setup_token_created=0
if [ ! -s "$DATA/setup-token" ]; then
  if [ -n "${PBX_SETUP_TOKEN:-}" ]; then
    setup_token="${PBX_SETUP_TOKEN}"
  else
    setup_token="$(openssl rand -hex 8 | tr '[:lower:]' '[:upper:]' | sed 's/\(....\)/\1-/g; s/-$//')"
  fi
  umask 077
  printf '%s\n' "$setup_token" >"$DATA/setup-token"
  setup_token_created=1
fi

# The security log must exist before fail2ban starts polling it.
touch "$DATA/log/security" "$DATA/log/messages" "$DATA/log/queue_log" "$DATA/log/sip"

# Custom prompts live under /data/sounds, but Asterisk's sound search path is image-owned.
# Link the English (default) sound directory at the persistent upload directory.
ln -snf "$DATA/sounds" /var/lib/asterisk/sounds/custom
if [ -d /var/lib/asterisk/sounds/en ]; then
  ln -snf "$DATA/sounds" /var/lib/asterisk/sounds/en/custom
fi

# /etc/asterisk always points at the persistent rendered tree.
if [ -e /etc/asterisk ] && [ ! -L /etc/asterisk ]; then
  rm -rf /etc/asterisk
fi
ln -snf "$DATA/config/asterisk" /etc/asterisk

# Initialise the configuration Git repository exactly once, then commit the bootstrap
# model and rendered tree together.
if [ ! -d "$DATA/config/.git" ]; then
  # Run Git as the API owner. The config tree is pbx-owned, and running as root would trigger
  # Git's dubious-ownership protection (and leave root-owned objects in the repository).
  s6-setuidgid pbx git init -q -b main "$DATA/config"
  s6-setuidgid pbx git -C "$DATA/config" \
    -c user.name="BetterPBX" -c user.email="pbx@localhost" add -A
  s6-setuidgid pbx git -C "$DATA/config" \
    -c user.name="BetterPBX" -c user.email="pbx@localhost" \
    commit -q -m "Bootstrap: initial safe configuration"
  log "initialised configuration Git repository"
fi

# Fix ownership after all files have been created. Configuration is API-owned and read-only
# to Asterisk (group read); logs, voicemail, and sounds are Asterisk-owned with group access
# for the API.
chown -R pbx:pbx "$DATA/config" "$DATA/runtime"
chown -R asterisk:pbx "$DATA/log" "$DATA/voicemail" "$DATA/sounds"
chown pbx:pbx "$DATA/setup-token" "$DATA/runtime/internal-token"
chown asterisk:pbx "$DATA/runtime/tls" "$DATA/runtime/tls/sip.key" "$DATA/runtime/tls/sip.crt"

chmod 0750 "$DATA/config"
chmod -R u+rwX,g+rX,o-rwx "$DATA/config"
chmod 0750 "$DATA/runtime"
chmod -R u+rwX,g+rX,o-rwx "$DATA/runtime"
chmod 0770 "$DATA/log" "$DATA/voicemail" "$DATA/sounds"
chmod -R u+rwX,g+rwX,o-rwx "$DATA/log" "$DATA/voicemail" "$DATA/sounds"
chmod 0600 "$DATA/setup-token" "$DATA/runtime/internal-token"
chmod 0770 "$DATA/runtime/tls"
chmod 0600 "$DATA/runtime/tls/sip.key"
chmod 0640 "$DATA/runtime/tls/sip.crt"

if [ "$fresh_boot" -eq 1 ]; then
  log "first boot initialisation complete"
else
  log "existing /data detected; configuration and tokens left unchanged"
fi

if [ -s "$DATA/setup-token" ]; then
  setup_code="$(cat "$DATA/setup-token")"
  log "FIRST-RUN SETUP CODE: ${setup_code}"
  if [ "$setup_token_created" -eq 1 ]; then
    log "enter this code in the setup wizard; it is stored at /data/setup-token"
  else
    log "setup is still pending; the code above is unchanged from an earlier boot"
  fi
else
  log "setup is complete"
fi
