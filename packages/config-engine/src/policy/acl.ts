import { isCatchAllCidr, isCidr, type PbxModel } from '@better-pbx/shared';

import { renderConfig } from '../render/config-format.js';
import type { RuntimeState } from '../render/types.js';
import { SecurityPolicyError, type PolicyIssue } from './security.js';

const DEFAULT_PERMIT = '0.0.0.0/0.0.0.0';

/**
 * Render the runtime-only named ACL included by `acl.conf` and referenced by every PJSIP endpoint
 * as `acl = global-acl`.
 *
 * Rules are emitted most-restrictive-first: explicit denies and whitelist permits come before the
 * default permit-all, so an automatic ban is never overridden by a broad allow. Bans are runtime
 * state and are therefore never part of a Git snapshot.
 */
export function renderPjsipAcl(model: PbxModel, runtime: RuntimeState = {}): string {
  const bans = runtime.bannedCidrs ?? [];
  const issues: PolicyIssue[] = [];
  for (let index = 0; index < bans.length; index += 1) {
    const ban = bans[index] ?? '';
    if (!isCidr(ban)) {
      issues.push({
        code: 'invalid-cidr',
        path: `runtime.bannedCidrs[${index}]`,
        message: 'ban entry is not a valid IP or CIDR',
        severity: 'error',
      });
    } else if (isCatchAllCidr(ban)) {
      issues.push({
        code: 'catch-all-cidr',
        path: `runtime.bannedCidrs[${index}]`,
        message: 'a ban must not cover the whole internet',
        severity: 'error',
      });
    }
  }
  if (issues.length > 0) throw new SecurityPolicyError(issues);

  const sort = (values: string[]): string[] => [...values].sort((a, b) => a.localeCompare(b, 'en'));
  const lines = [
    ...sort(model.settings.security.whitelist).map((cidr) => `permit = ${cidr}`),
    ...sort(model.settings.security.blacklist).map((cidr) => `deny = ${cidr}`),
    ...sort(bans).map((cidr) => `deny = ${cidr}`),
    `permit = ${DEFAULT_PERMIT}`,
  ];

  return renderConfig(
    [
      'BetterPBX runtime PJSIP ACL. Generated by the API, never committed.',
      '',
      'Referenced by acl.conf and every endpoint. Explicit whitelist permits and blacklist/ban',
      'denies precede the default permit because authenticated endpoints must still be reachable.',
    ],
    [{ name: 'global-acl', lines }],
  );
}
