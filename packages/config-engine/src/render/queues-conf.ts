import type { PbxModel } from '@better-pbx/shared';

import { renderConfig, type ConfigSection } from './config-format.js';
import { extensionEndpoint, queueName } from '../model-lookup.js';

/**
 * Ring groups are queues. `timeout` is in milliseconds because app_queue waits that long before
 * moving from one member to the next; `ringTime` in the model is expressed in seconds.
 */
export function renderQueuesConf(model: PbxModel): string {
  const byId = new Map(model.extensions.map((extension) => [extension.id, extension]));
  const groups = model.ringGroups
    .slice()
    .sort((a, b) => a.number.localeCompare(b.number, 'en'));

  const sections: ConfigSection[] = [
    {
      name: 'general',
      lines: ['; Ring groups are rendered as queues. Do not edit this file by hand.'],
    },
  ];

  for (const group of groups) {
    const members = group.memberIds.flatMap((memberId) => {
      const extension = byId.get(memberId);
      return extension === undefined || !extension.enabled
        ? []
        : [`member => PJSIP/${extensionEndpoint(extension)}`];
    });

    sections.push({
      name: queueName(group.id),
      lines: [
        `strategy = ${group.strategy}`,
        `timeout = ${group.ringTime * 1000}`,
        'retry = 5',
        'ringinuse = no',
        'maxlen = 0',
        'announce-frequency = 0',
        `musicclass = ${group.musicOnHoldClassId ?? 'default'}`,
        ...members,
      ],
    });
  }

  return renderConfig(
    ['BetterPBX ring groups rendered as Asterisk queues.'],
    sections,
  );
}
