export function renderModulesConf(): string {
  const sections: ConfigSection[] = [
    {
      name: 'modules',
      lines: [
        'autoload = no',
        '',
        ...MODULES.map((line) =>
          line === '' ? '' : line.startsWith(';') ? line : `load = ${line}`,
        ),
      ],
    },
  ];

  return renderConfig(
    [
      'BetterPBX module policy.',
      '',
      'Autoload is deliberately disabled. Only the modules listed here are loaded. The curated',
      'build omits legacy channel drivers, ARI/Stasis, HTTP, AMI helpers, and dialplan',
      'applications that can execute host commands (app_system, app_exec, app_disa, func_shell).',
    ],
    sections,
  );
}
