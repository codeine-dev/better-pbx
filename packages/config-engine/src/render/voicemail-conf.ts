import type { PbxModel } from '@better-pbx/shared';

import { renderConfig, sanitizeValue, type ConfigSection } from './config-format.js';

/** One mailbox per voicemail-enabled extension, ordered by number for deterministic output. */
export function renderVoicemailConf(model: PbxModel): string {
  const mailboxes = model.extensions
    .filter((extension) => extension.enabled && extension.voicemail.enabled)
    .slice()
    .sort((a, b) => a.number.localeCompare(b.number, 'en'))
    .map((extension) => {
      const pin = extension.voicemail.pin;
      if (pin === undefined) {
        throw new Error(`voicemail is enabled for extension ${extension.number} without a PIN`);
      }
      const name = sanitizeValue(extension.displayName);
      const email = extension.voicemail.email;
      return `${extension.number} => ${pin},${name}${email === undefined ? '' : `,${sanitizeValue(email)}`}`;
    });

  const sections: ConfigSection[] = [
    {
      name: 'general',
      lines: [
        'format = ulaw',
        'serveremail = pbx@localhost',
        `maxmsg = ${model.settings.voicemail.maxMessages}`,
        `maxsecs = ${model.settings.voicemail.maxSeconds}`,
        'emaildateformat = %A, %B %d, %Y at %r',
        'attach = no',
      ],
    },
    { name: 'default', lines: mailboxes },
  ];

  return renderConfig(
    [
      'BetterPBX voicemail.',
      '',
      'Voicemail is stored at /data/voicemail because asterisk.conf sets astspooldir=/data.',
      'Mailboxes are generated from the typed model; do not edit this file by hand.',
    ],
    sections,
  );
}
